internal fun fixtureNode(
    id: Int,
    pid: Int,
    className: String,
    left: Int = 0,
    top: Int = 0,
    right: Int = 0,
    bottom: Int = 0,
    index: Int = 0,
    depth: Int = 0,
    text: String? = null,
    desc: String? = null,
    viewId: String? = null,
    vid: String? = null,
    clickable: Boolean = false,
    childCount: Int = 0,
): NodeInfo = NodeInfo(
    id = id,
    pid = pid,
    idQf = null,
    textQf = null,
    attr = AttrInfo(
        id = viewId,
        vid = vid,
        name = className,
        text = text,
        desc = desc,
        clickable = clickable,
        focusable = false,
        checkable = false,
        checked = null,
        editable = false,
        longClickable = false,
        visibleToUser = true,
        left = left,
        top = top,
        right = right,
        bottom = bottom,
        width = right - left,
        height = bottom - top,
        childCount = childCount,
        index = index,
        depth = depth,
    ),
)
